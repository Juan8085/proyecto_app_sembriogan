export const obtenerMunicipios = (departamento) => {
  if (!departamento) return MUNICIPIOS_POR_DEPARTAMENTO['Huila'];
  return MUNICIPIOS_POR_DEPARTAMENTO[departamento] || ['Otro'];
};

export const formatearUbicacion = (municipio, departamento) => {
  const m = (municipio || '').trim();
  const d = (departamento || '').trim();
  if (m && d && !m.toLowerCase().includes(d.toLowerCase())) {
    return `${m}, ${d}`;
  }
  return m || d || 'Colombia';
};

